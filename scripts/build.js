#!/usr/bin/env node

// Builds one plugin folder per bundle under plugins/, plus the marketplace file each host reads.
//
//   plugins/<bundle>/plugin.json                  Agent Plugins schema (Codex primary format)
//   plugins/<bundle>/.claude-plugin/plugin.json   Claude Code
//   plugins/<bundle>/.github/plugin/plugin.json   GitHub Copilot
//   plugins/<bundle>/skills/<name>/               byte-identical copy of src/skills/<name>/
//   plugins/<bundle>/skills/<command>/            command rendered as a user-invoked skill, for every host
//   plugins/<bundle>/guides/<guide>.md            walkthrough copied from src/guides/
//   plugins/<bundle>/agents/<name>.md             Claude Code agent
//   plugins/<bundle>/.github/agents/<name>.agent.md  GitHub Copilot agent
//   plugins/<bundle>/codex/agents/<name>.toml     Codex agent, copied into .codex/agents/ by the user
//   plugins/<bundle>/.mcp.json, mcp.json          MCP servers for Claude Code and Codex
//
//   .claude-plugin/marketplace.json    Claude Code
//   .agents/plugins/marketplace.json   Codex
//   .github/plugin/marketplace.json    GitHub Copilot
//
//   rules/<host>/...                   rules laid out as each host expects them in a project, to copy in
//   hooks/copilot/...                  Copilot hooks to copy in; Claude Code hooks are plugins/<hook>/
//   plugins/<pack>/                    one plugin per orchestration pack, for every host
//
//   catalog/*.md                       the full skill, command and agent tables
//   README.md                          the sections between START_/END_ markers only
//
// Skill copies are real files, not symlinks: Codex drops symlinks when it caches a plugin.
// Everything written here is generated; edit src/, bundles.yaml or package.json instead.
//
// --check   compare against disk and fail on any difference, write nothing

const fs = require('fs');
const path = require('path');
const { createLogger } = require('./lib/log');
const {
  repoRoot,
  skillsRoot,
  listFiles,
  listSkills,
  listAgents,
  listRules,
  listCommands,
  listGuides,
  listHooks,
  listPacks,
  listMcpServers,
  loadBundles,
  loadPackage,
} = require('./lib/collection');
const {
  claudeAgent,
  copilotAgent,
  codexAgent,
  codexAgentName,
  commandSkill,
  commandOpenAiYaml,
  orchestratorSkill,
  copilotRule,
  claudeRule,
  codexRulesIndex,
  mcpConfig,
} = require('./lib/hosts');
const { renderReadme, renderCatalog, CATALOG_DIR } = require('./lib/readme');

const log = createLogger('build');
const checkOnly = process.argv.includes('--check');

const MARKETPLACE = 'jaktestowac';
const DISPLAY_NAME = 'Awesome Agents for Quality';
const AGENT_PLUGINS_SCHEMA = 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json';
const PLUGINS_DIR = 'plugins';
const RULES_DIR = 'rules';
const HOOKS_DIR = 'hooks';
const GENERATED_DIRS = [PLUGINS_DIR, RULES_DIR, HOOKS_DIR, CATALOG_DIR];
const MARKETPLACE_FILES = [
  '.claude-plugin/marketplace.json',
  '.agents/plugins/marketplace.json',
  '.github/plugin/marketplace.json',
];

const pkg = loadPackage();
const bundles = loadBundles();
const repoUrl = pkg.repository.url.replace(/\.git$/, '');
const author = { name: pkg.author, url: 'https://jaktestowac.pl' };

// path (relative to repo root) -> Buffer
const expected = new Map();

function json(value) {
  return Buffer.from(JSON.stringify(value, null, 2) + '\n');
}

function keywordsFor(bundle) {
  return [
    ...new Set(['testing', 'quality-engineering', ...bundle.split('-').filter((w) => w.length > 2)]),
  ];
}

function pluginReadme(bundle, spec, agents, commands, servers) {
  const out = [
    '<!-- Generated by scripts/build.js from bundles.yaml. Do not edit. -->',
    '',
    `# ${spec.icon || '📦'} ${bundle}`,
    '',
    spec.description,
    '',
    `Install: \`${bundle}@${MARKETPLACE}\`. See the [quick start](${repoUrl}#-quick-start) for each tool.`,
    '',
    ...(spec.guides || []).flatMap((name) => [
      `📘 **Guide:** [${guidesByName.get(name).title}](guides/${name}.md) shows how the pieces work together.`,
      '',
    ]),
    '## Skills',
    '',
    ...spec.skills.map((name) => `- [\`${name}\`](skills/${name}/SKILL.md)`),
  ];
  if (commands.length) {
    out.push(
      '',
      '## Commands',
      '',
      'Run these yourself: `/name` in Claude Code and GitHub Copilot, `$name` in Codex. The agent never starts them on its own.',
      '',
      ...commands.map(({ slug, data }) => `- [\`${slug}\`](skills/${slug}/SKILL.md): ${data.title || slug}`),
    );
  }
  if (agents.length) {
    out.push(
      '',
      '## Agents',
      '',
      '| Agent | Claude Code | GitHub Copilot | Codex |',
      '| --- | --- | --- | --- |',
      ...agents.map(
        ({ data }) =>
          `| ${data.title || data.name} | [\`${data.name}\`](agents/${data.name}.md) | [\`${data.name}\`](.github/agents/${data.name}.agent.md) | [\`${codexAgentName(data.name)}\`](codex/agents/${data.name}.toml) |`,
      ),
      '',
      'Claude Code and GitHub Copilot load these agents with the plugin.',
      'Codex does not load agents from plugins: copy the files from [`codex/agents/`](codex/agents/) into your project\'s `.codex/agents/` or into `~/.codex/agents/`.',
    );
  }
  if (servers.length) {
    out.push(
      '',
      '## MCP servers',
      '',
      ...servers.map((s) => `- \`${s.name}\`: \`${[s.command, ...(s.args || [])].join(' ')}\``),
      '',
      'Claude Code and Codex start these from the plugin. In GitHub Copilot, add them to your MCP configuration yourself.',
    );
  }
  return Buffer.from(`${out.join('\n')}\n`);
}

function rulesReadme(rules) {
  const out = [
    '<!-- Generated by scripts/build.js from src/rules/. Do not edit. -->',
    '',
    '# 📏 Rules',
    '',
    'Coding rules your agent applies automatically while it edits matching files. Each folder below mirrors a project layout: copy its contents into the root of your project.',
    '',
    '| Tool | Copy | Result |',
    '| --- | --- | --- |',
    '| GitHub Copilot | [`copilot/`](copilot/) | `.github/instructions/*.instructions.md`, scoped by `applyTo` |',
    '| Claude Code | [`claude/`](claude/) | `.claude/rules/*.md`, scoped by `paths` |',
    '| OpenAI Codex | [`codex/`](codex/) | `.agents/rules/*.md` plus an `AGENTS.md` index. If your project already has an `AGENTS.md`, append the index to it instead of overwriting it. |',
    '',
    'Copy only the rules you want. In Codex, also drop their rows from the index.',
    '',
    '## Rules',
    '',
    '| Rule | Applies to | What it covers | Copilot | Claude Code | Codex |',
    '| --- | --- | --- | :---: | :---: | :---: |',
    ...rules.map(
      ({ slug, data }) =>
        `| \`${slug}\` | ${data.applyTo.map((g) => `\`${g}\``).join('<br>')} | ${data.description.replace(/\|/g, '\\|')} | ` +
        `[📄](copilot/.github/instructions/${slug}.instructions.md) | ` +
        `[📄](claude/.claude/rules/${slug}.md) | ` +
        `[📄](codex/.agents/rules/${slug}.md) |`,
    ),
    '',
    'Back to the [catalog](../catalog/README.md) or the [main README](../README.md).',
  ];
  return Buffer.from(`${out.join('\n')}\n`);
}

function hookPluginReadme(hook) {
  const out = [
    '<!-- Generated by scripts/build.js from src/hooks/. Do not edit. -->',
    '',
    `# 🪝 ${hook.data.title || hook.slug}`,
    '',
    hook.data.description,
    '',
    `Install in Claude Code: \`/plugin install ${hook.slug}@${MARKETPLACE}\`. The hook runs \`node\`, so Node.js must be on your PATH.`,
  ];
  if (hook.shared.length) {
    out.push(
      '',
      `To change the configuration, copy [\`hooks/${hook.shared[0]}\`](hooks/${hook.shared[0]}) to \`.claude/${hook.shared[0]}\` in your project and edit it there. The project copy wins over the one bundled with the plugin.`,
    );
  }
  return Buffer.from(`${out.join('\n')}\n`);
}

function packReadme(pack, orchestrator, helpers, servers) {
  const out = [
    '<!-- Generated by scripts/build.js from src/packs/. Do not edit. -->',
    '',
    `# 🎼 ${pack.data.title}`,
    '',
    pack.data.description,
    '',
    `Install: \`${pack.slug}@${MARKETPLACE}\`. See the [quick start](${repoUrl}#-quick-start) for each tool.`,
    '',
    '## Start the pack',
    '',
    '| Tool | How |',
    '| --- | --- |',
    `| GitHub Copilot | Pick **${orchestrator.data.title}** in the agent dropdown and describe the job. It hands off to the other agents. |`,
    `| Claude Code | Run \`/${pack.slug}\` followed by the job. The command coordinates; the agents below do the work. |`,
    `| OpenAI Codex | Copy [\`codex/agents/\`](codex/agents/) into \`.codex/agents/\`, then run \`$${pack.slug}\` followed by the job. |`,
    '',
    'Claude Code and Codex agents cannot start other agents, so there the orchestrator is a command that runs in your conversation.',
    '',
    '## Agents',
    '',
    '| Agent | Name in Claude Code and Codex | What it does |',
    '| --- | --- | --- |',
    `| **${orchestrator.data.title}** (orchestrator) | \`/${pack.slug}\` command | ${orchestrator.data.description.replace(/\|/g, '\\|')} |`,
    ...helpers.map(
      ({ data }) => `| ${data.title} | \`${data.name}\` / \`${codexAgentName(data.name)}\` | ${data.description.replace(/\|/g, '\\|')} |`,
    ),
  ];
  if (servers.length) {
    out.push(
      '',
      '## MCP servers',
      '',
      ...servers.map((s) => `- \`${s.name}\`: \`${[s.command, ...(s.args || [])].join(' ')}\``),
      '',
      'Claude Code and Codex start these from the plugin. In GitHub Copilot, the agents that need them configure them themselves.',
    );
  }
  if (pack.guide) out.push('', `How the pack works, step by step: [GUIDE.md](GUIDE.md).`);
  return Buffer.from(`${out.join('\n')}\n`);
}

function hooksReadme(hooks) {
  const out = [
    '<!-- Generated by scripts/build.js from src/hooks/. Do not edit. -->',
    '',
    '# 🪝 Hooks',
    '',
    'Hooks run a script when something happens in a session: it starts, a tool is about to run, a file was edited.',
    '',
    '| Tool | How to install |',
    '| --- | --- |',
    `| Claude Code | Each hook is its own plugin: \`/plugin install <hook>@${MARKETPLACE}\`. Needs Node.js on your PATH. |`,
    '| GitHub Copilot | Copy the hook\'s folder from [`copilot/.github/hooks/`](copilot/.github/hooks/) into your project\'s `.github/hooks/`. The bash scripts need `jq`; PowerShell needs nothing extra. |',
    '| OpenAI Codex | Not supported yet: Codex only runs plugin hooks for manually installed desktop plugins. |',
    '',
    '## Hooks',
    '',
    '| Hook | What it does | Claude Code | Copilot |',
    '| --- | --- | :---: | :---: |',
    ...hooks.map((hook) => {
      const claude = hook.data.hosts.includes('claude') ? `[plugin](../${PLUGINS_DIR}/${hook.slug}/)` : '—';
      const copilot = hook.data.hosts.includes('copilot') ? `[folder](copilot/.github/hooks/${hook.slug}/)` : '—';
      return `| \`${hook.slug}\` | ${hook.data.description} | ${claude} | ${copilot} |`;
    }),
  ];
  return Buffer.from(`${out.join('\n')}\n`);
}

const agentsByName = new Map(listAgents().map((agent) => [agent.slug, agent]));
const commandsByName = new Map(listCommands().map((command) => [command.slug, command]));
const guidesByName = new Map(listGuides().map((guide) => [guide.slug, guide]));
const serversByName = new Map(listMcpServers().map((server) => [server.slug, server.data]));

for (const [bundle, spec] of Object.entries(bundles)) {
  const root = `${PLUGINS_DIR}/${bundle}`;
  const skills = spec.skills || [];
  const agents = (spec.agents || []).map((name) => agentsByName.get(name));
  const commands = (spec.commands || []).map((name) => commandsByName.get(name));
  // A bundle needs every MCP server its agents and commands use, plus any it lists itself.
  const serverNames = [
    ...new Set([...(spec.mcp || []), ...[...agents, ...commands].flatMap((item) => item.data.mcp || [])]),
  ].sort();
  const servers = serverNames.map((name) => serversByName.get(name));
  const common = {
    name: bundle,
    version: pkg.version,
    description: spec.description,
    author,
    homepage: repoUrl,
    repository: repoUrl,
    license: pkg.license,
    keywords: keywordsFor(bundle),
  };

  expected.set(`${root}/plugin.json`, json({ $schema: AGENT_PLUGINS_SCHEMA, ...common }));
  expected.set(`${root}/.claude-plugin/plugin.json`, json(common));
  expected.set(
    `${root}/.github/plugin/plugin.json`,
    json({
      ...common,
      ...(agents.length ? { agents: ['./.github/agents/'] } : {}),
      skills: [...skills, ...commands.map((c) => c.slug)].map((name) => `./skills/${name}/`),
    }),
  );
  expected.set(`${root}/README.md`, pluginReadme(bundle, spec, agents, commands, servers));

  // Guides are walkthroughs that tie a plugin's pieces into one workflow. They link relative to guides/.
  for (const name of spec.guides || []) {
    expected.set(`${root}/guides/${name}.md`, fs.readFileSync(guidesByName.get(name).file));
  }

  // Commands ship as user-invoked skills next to the real ones.
  for (const command of commands) {
    expected.set(`${root}/skills/${command.slug}/SKILL.md`, Buffer.from(commandSkill(command)));
    expected.set(`${root}/skills/${command.slug}/agents/openai.yaml`, Buffer.from(commandOpenAiYaml(command)));
  }

  // Claude Code scans agents/ recursively, so Copilot's files live outside it.
  for (const agent of agents) {
    expected.set(`${root}/agents/${agent.slug}.md`, Buffer.from(claudeAgent(agent)));
    expected.set(`${root}/.github/agents/${agent.slug}.agent.md`, Buffer.from(copilotAgent(agent)));
    expected.set(`${root}/codex/agents/${agent.slug}.toml`, Buffer.from(codexAgent(agent)));
  }
  if (servers.length) {
    expected.set(`${root}/.mcp.json`, Buffer.from(mcpConfig(servers)));
    expected.set(`${root}/mcp.json`, Buffer.from(mcpConfig(servers)));
  }

  for (const name of skills) {
    const source = path.join(skillsRoot, name);
    for (const file of listFiles(source)) {
      expected.set(`${root}/skills/${name}/${file}`, fs.readFileSync(path.join(source, file)));
    }
  }
}

const entries = Object.entries(bundles);
const metadata = { description: pkg.description, version: pkg.version };

// Hooks: each hook is its own opt-in Claude Code plugin, so installing a bundle never adds hooks
// behind your back. Copilot gets a copy-in folder, as for rules. Codex only runs plugin hooks for
// manually installed desktop plugins, so it is left out.
const hooks = listHooks();
for (const hook of hooks) {
  const hosts = hook.data.hosts;
  if (hosts.includes('copilot')) {
    const target = `${HOOKS_DIR}/copilot/.github/hooks/${hook.slug}`;
    for (const file of listFiles(path.join(hook.dir, 'copilot'))) {
      expected.set(`${target}/${file}`, fs.readFileSync(path.join(hook.dir, 'copilot', file)));
    }
    for (const file of hook.shared) expected.set(`${target}/${file}`, fs.readFileSync(path.join(hook.dir, file)));
  }
  if (hosts.includes('claude')) {
    const root = `${PLUGINS_DIR}/${hook.slug}`;
    expected.set(
      `${root}/.claude-plugin/plugin.json`,
      json({
        name: hook.slug,
        version: pkg.version,
        description: hook.data.description,
        author,
        homepage: repoUrl,
        repository: repoUrl,
        license: pkg.license,
        keywords: ['hooks', 'testing', 'quality-engineering'],
      }),
    );
    for (const file of listFiles(path.join(hook.dir, 'claude'))) {
      expected.set(`${root}/hooks/${file}`, fs.readFileSync(path.join(hook.dir, 'claude', file)));
    }
    for (const file of hook.shared) expected.set(`${root}/hooks/${file}`, fs.readFileSync(path.join(hook.dir, file)));
    expected.set(`${root}/README.md`, hookPluginReadme(hook));
  }
}
if (hooks.length) expected.set(`${HOOKS_DIR}/README.md`, hooksReadme(hooks));
const claudeHookPlugins = hooks.filter((hook) => hook.data.hosts.includes('claude'));

// Orchestration packs: one opt-in plugin per pack, for every host. Copilot runs the orchestrator as an
// agent with handoffs. Claude Code and Codex can't nest subagents, so their orchestrator is a command
// (skills/<pack>/) that runs in the main conversation; only the helpers become agents there.
const packs = listPacks();
for (const pack of packs) {
  const root = `${PLUGINS_DIR}/${pack.slug}`;
  const orchestrator = pack.agents.find((a) => a.slug === pack.data.orchestrator);
  const helpers = pack.agents.filter((a) => a !== orchestrator);
  const serverNames = [...new Set(pack.agents.flatMap((a) => a.data.mcp || []))].sort();
  const servers = serverNames.map((name) => serversByName.get(name));
  const common = {
    name: pack.slug,
    version: pkg.version,
    description: pack.data.description,
    author,
    homepage: repoUrl,
    repository: repoUrl,
    license: pkg.license,
    keywords: ['orchestration', 'subagents', 'testing', 'quality-engineering'],
  };
  expected.set(`${root}/plugin.json`, json({ $schema: AGENT_PLUGINS_SCHEMA, ...common }));
  expected.set(`${root}/.claude-plugin/plugin.json`, json(common));
  expected.set(`${root}/.github/plugin/plugin.json`, json({ ...common, agents: ['./.github/agents/'] }));
  for (const agent of pack.agents) {
    expected.set(`${root}/.github/agents/${agent.slug}.agent.md`, Buffer.from(copilotAgent(agent, { nameFromTitle: true })));
  }
  for (const agent of helpers) {
    expected.set(`${root}/agents/${agent.slug}.md`, Buffer.from(claudeAgent(agent)));
    expected.set(`${root}/codex/agents/${agent.slug}.toml`, Buffer.from(codexAgent(agent)));
  }
  expected.set(`${root}/skills/${pack.slug}/SKILL.md`, Buffer.from(orchestratorSkill(pack, orchestrator, helpers)));
  expected.set(
    `${root}/skills/${pack.slug}/agents/openai.yaml`,
    Buffer.from(commandOpenAiYaml({ data: { name: pack.slug, title: pack.data.title } })),
  );
  if (servers.length) {
    expected.set(`${root}/.mcp.json`, Buffer.from(mcpConfig(servers)));
    expected.set(`${root}/mcp.json`, Buffer.from(mcpConfig(servers)));
  }
  if (pack.guide) expected.set(`${root}/GUIDE.md`, fs.readFileSync(pack.guide));
  expected.set(`${root}/README.md`, packReadme(pack, orchestrator, helpers, servers));
}
const packEntries = packs.map((pack) => [pack.slug, pack.data.description]);

expected.set(
  '.claude-plugin/marketplace.json',
  json({
    $schema: 'https://json.schemastore.org/claude-code-marketplace.json',
    name: MARKETPLACE,
    owner: author,
    metadata,
    plugins: [
      ...entries.map(([bundle, spec]) => ({
        name: bundle,
        source: `./${PLUGINS_DIR}/${bundle}`,
        description: spec.description,
        version: pkg.version,
      })),
      ...packEntries.map(([name, description]) => ({
        name,
        source: `./${PLUGINS_DIR}/${name}`,
        description,
        version: pkg.version,
      })),
      ...claudeHookPlugins.map((hook) => ({
        name: hook.slug,
        source: `./${PLUGINS_DIR}/${hook.slug}`,
        description: hook.data.description,
        version: pkg.version,
      })),
    ],
  }),
);
// Bundles and packs ship to every host; hook plugins are Claude Code only.
const everyHost = [...entries.map(([bundle, spec]) => [bundle, spec.description]), ...packEntries];
expected.set(
  '.agents/plugins/marketplace.json',
  json({
    name: MARKETPLACE,
    interface: { displayName: DISPLAY_NAME },
    plugins: everyHost.map(([name, description]) => ({
      name,
      version: pkg.version,
      description,
      source: { source: 'local', path: `./${PLUGINS_DIR}/${name}` },
      policy: { installation: 'AVAILABLE', authentication: 'ON_INSTALL' },
      category: 'Productivity',
    })),
  }),
);
expected.set(
  '.github/plugin/marketplace.json',
  json({
    name: MARKETPLACE,
    metadata,
    owner: author,
    plugins: everyHost.map(([name, description]) => ({
      name,
      source: `${PLUGINS_DIR}/${name}`,
      description,
      version: pkg.version,
    })),
  }),
);

// Rules are not a plugin component in any host, so they ship as folders that mirror each host's
// project layout: copying rules/<host>/ into a project root puts every file where that host reads it.
const rules = listRules();
const CODEX_RULES_DIR = '.agents/rules';
for (const rule of rules) {
  expected.set(`${RULES_DIR}/copilot/.github/instructions/${rule.slug}.instructions.md`, Buffer.from(copilotRule(rule)));
  expected.set(`${RULES_DIR}/claude/.claude/rules/${rule.slug}.md`, Buffer.from(claudeRule(rule)));
  expected.set(`${RULES_DIR}/codex/${CODEX_RULES_DIR}/${rule.slug}.md`, Buffer.from(rule.body));
}
if (rules.length) {
  expected.set(`${RULES_DIR}/codex/AGENTS.md`, Buffer.from(codexRulesIndex(rules, CODEX_RULES_DIR)));
  expected.set(`${RULES_DIR}/README.md`, rulesReadme(rules));
}

// README.md (only the marked sections) and the catalog pages that hold the long tables.
const skillsByName = new Map(listSkills().map((skill) => [skill.folder, skill]));
const docsContext = {
  bundles,
  skills: [...skillsByName.values()],
  skillsByName,
  agents: [...agentsByName.values()],
  agentsByName,
  commands: [...commandsByName.values()],
  commandsByName,
  rules,
  hooks,
  packs,
  guidesByName,
};
expected.set('README.md', Buffer.from(renderReadme(fs.readFileSync(path.join(repoRoot, 'README.md'), 'utf8'), docsContext)));
for (const [file, content] of Object.entries(renderCatalog(docsContext))) expected.set(file, Buffer.from(content));

// Compare with what is on disk: everything under plugins/ and rules/, the marketplace files and the README.
const onDisk = new Set([
  ...GENERATED_DIRS.flatMap((dir) => listFiles(path.join(repoRoot, dir)).map((f) => `${dir}/${f}`)),
  ...MARKETPLACE_FILES.filter((f) => fs.existsSync(path.join(repoRoot, f))),
  'README.md',
]);

const added = [];
const changed = [];
const stale = [...onDisk].filter((f) => !expected.has(f)).sort();
for (const [file, content] of expected) {
  if (!onDisk.has(file)) added.push(file);
  else if (!fs.readFileSync(path.join(repoRoot, file)).equals(content)) changed.push(file);
}

// Bundles, packs and Claude Code hook plugins.
const pluginCount = entries.length + packs.length + claudeHookPlugins.length;

log.intro(checkOnly ? 'checking generated files are up to date' : `building ${pluginCount} plugins`);

// Every relative link in the docs this build writes must land on a generated file or a file in the repo.
// Copied skill files are skipped: their templates hold example links into the user's own project.
function brokenLinks() {
  const isDoc = (file) =>
    file === 'README.md' ||
    /^(rules|hooks)\/README\.md$/.test(file) ||
    file.startsWith(`${CATALOG_DIR}/`) ||
    new RegExp(`^${PLUGINS_DIR}/[^/]+/(README\\.md|GUIDE\\.md|guides/[^/]+\\.md)$`).test(file);
  const dirs = new Set();
  for (const file of expected.keys()) {
    for (let dir = path.posix.dirname(file); dir !== '.'; dir = path.posix.dirname(dir)) dirs.add(dir);
  }
  const found = [];
  for (const [file, content] of expected) {
    if (!isDoc(file)) continue;
    const text = content.toString('utf8').replace(/```[\s\S]*?```/g, '');
    for (const [, href] of text.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
      if (/^(https?:|mailto:|#)/.test(href)) continue;
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(file), decodeURIComponent(href.split('#')[0]))).replace(/\/$/, '');
      if (expected.has(target) || dirs.has(target)) continue;
      const generated = GENERATED_DIRS.some((dir) => target === dir || target.startsWith(`${dir}/`));
      if (!generated && fs.existsSync(path.join(repoRoot, target))) continue;
      found.push(`${file}: link to ${href} does not resolve`);
    }
  }
  return found;
}
const linkErrors = brokenLinks();

if (checkOnly || linkErrors.length) {
  const errors = checkOnly
    ? [
        ...added.map((f) => `${f}: missing`),
        ...changed.map((f) => `${f}: out of date`),
        ...stale.map((f) => `${f}: no longer generated`),
      ]
    : [];
  if (errors.length) errors.push('run `npm run build` and commit the result');
  log.finish({ errors: [...linkErrors, ...errors], ok: `(${expected.size} files up to date)` });
}

for (const file of [...added, ...changed]) {
  const target = path.join(repoRoot, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, expected.get(file));
}
for (const file of stale) fs.rmSync(path.join(repoRoot, file));
// Drop directories emptied by stale removals.
function pruneEmpty(dir, top) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) pruneEmpty(path.join(dir, entry.name), top);
  }
  if (dir !== top && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
}
for (const dir of GENERATED_DIRS) {
  const top = path.join(repoRoot, dir);
  if (fs.existsSync(top)) pruneEmpty(top, top);
}

if (added.length) log.added(`${added.length} files written`);
if (changed.length) log.change('~', `${changed.length} files updated`);
if (stale.length) {
  log.removed(`${stale.length} files removed`);
  log.names(stale);
}
log.finish({
  ok: `(${pluginCount} plugins, ${expected.size} files, ${expected.size - added.length - changed.length} unchanged)`,
  next: added.length || changed.length || stale.length ? ['npm run check'] : [],
});
