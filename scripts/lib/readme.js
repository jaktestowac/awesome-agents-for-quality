// Generated documentation:
//   - the sections of README.md between <!-- START_X --> and <!-- END_X --> markers; everything outside
//     the markers is hand-written and left alone
//   - the catalog pages under catalog/, which hold the long tables so the README stays readable
//
// Table renderers take `base`, the path from the page they land in back to the repo root, so the same
// table links correctly from README.md ('') and from catalog/*.md ('../').

const fs = require('fs');
const path = require('path');

const SECTIONS = ['BADGES', 'PLUGINS', 'GUIDES', 'SKILLS', 'COMMANDS', 'AGENTS', 'PACKS', 'RULES', 'HOOKS'];
const CATALOG_DIR = 'catalog';
const GENERATED = '<!-- Generated by scripts/build.js. Do not edit. -->';

// What an agent may do, shown as icons in the agents table.
const CAPABILITY_ICONS = { edit: '✏️', execute: '▶️', web: '🌐', agent: '🤝' };
const MCP_ICONS = { playwright: '🎭' };

function firstSentence(text) {
  return text.split(/(?<=[.!?])\s+(?=[A-Z])/)[0].replace(/\|/g, '\\|');
}

function count(items, noun) {
  return `${items.length} ${noun}${items.length === 1 ? '' : 's'}`;
}

// --- tables -------------------------------------------------------------------------------------

function skillsTables({ bundles, skillsByName }, base) {
  const out = [];
  for (const [bundle, spec] of Object.entries(bundles)) {
    // Plain headings keep the anchors predictable: #qa-core, #test-automation, ...
    out.push(
      `## ${bundle}`,
      '',
      `${spec.icon || '📦'} ${spec.description} Install the whole plugin with \`${bundle}@jaktestowac\`.`,
      '',
      '| Skill | What it does | Extras |',
      '| --- | --- | :---: |',
    );
    for (const name of spec.skills || []) {
      const skill = skillsByName.get(name);
      const extras = fs.existsSync(path.join(skill.dir, 'resources'))
        ? `[📎](${base}src/skills/${name}/resources/ "Browse resources")`
        : '';
      out.push(`| [\`${name}\`](${base}src/skills/${name}/SKILL.md) | ${firstSentence(skill.data.description)} | ${extras} |`);
    }
    out.push('');
  }
  return out.join('\n').trimEnd();
}

function commandsTable({ bundles, commandsByName }, base) {
  const out = ['| Command | What it does | Hands off to | Plugin |', '| --- | --- | --- | --- |'];
  for (const [bundle, spec] of Object.entries(bundles)) {
    for (const name of spec.commands || []) {
      const { data } = commandsByName.get(name);
      const agent = data.agent ? `[\`${data.agent}\`](${base}src/agents/${data.agent}.md)` : '';
      out.push(`| [\`/${name}\`](${base}src/commands/${name}.md) | ${firstSentence(data.description)} | ${agent} | \`${bundle}\` |`);
    }
  }
  return out.join('\n');
}

function agentsTable({ bundles, agentsByName }, base) {
  const out = ['| Agent | What it does | Can | Plugin |', '| --- | --- | :---: | --- |'];
  for (const [bundle, spec] of Object.entries(bundles)) {
    for (const name of spec.agents || []) {
      const { data } = agentsByName.get(name);
      const can = [
        ...data.capabilities.map((cap) => CAPABILITY_ICONS[cap]).filter(Boolean),
        ...(data.mcp || []).map((server) => MCP_ICONS[server] || '🔌'),
      ].join(' ');
      out.push(
        `| **[${data.title || name}](${base}src/agents/${name}.md)**<br>\`${name}\` | ${firstSentence(data.description)} | ${can} | \`${bundle}\` |`,
      );
    }
  }
  return out.join('\n');
}

// --- README sections ----------------------------------------------------------------------------

function badges({ skills, commands, agents, bundles }) {
  const badge = (label, message, color, logo) =>
    `<img alt="${label}: ${message}" src="https://img.shields.io/badge/${encodeURIComponent(label)}-${encodeURIComponent(message)}-${color}?style=for-the-badge${logo ? `&logo=${logo}&logoColor=white` : ''}">`;
  return [
    '<p align="center">',
    `  ${badge('skills', String(skills.length), '7C3AED')}`,
    `  ${badge('commands', String(commands.length), '0D9488')}`,
    `  ${badge('agents', String(agents.length), 'DB2777')}`,
    `  ${badge('plugins', String(Object.keys(bundles).length), '2563EB')}`,
    `  ${badge('license', 'MIT', '16A34A')}`,
    '</p>',
    '<p align="center">',
    `  ${badge('GitHub Copilot', 'ready', '000000', 'githubcopilot')}`,
    `  ${badge('Claude Code', 'ready', 'D97757', 'claude')}`,
    `  ${badge('OpenAI Codex', 'ready', '412991')}`,
    `  ${badge('Agent Skills', 'standard', '0EA5E9')}`,
    '</p>',
  ].join('\n');
}

function plugins({ bundles }) {
  const rows = Object.entries(bundles).map(
    ([bundle, spec]) =>
      `| ${spec.icon || '📦'} **[${bundle}](plugins/${bundle}/)** | ${spec.description} | ${(spec.skills || []).length} | ${(spec.commands || []).length} | ${(spec.agents || []).length} | \`${bundle}@jaktestowac\` |`,
  );
  return [
    '| Plugin | What it covers | Skills | Commands | Agents | Install id |',
    '| --- | --- | :---: | :---: | :---: | --- |',
    ...rows,
  ].join('\n');
}

function skillsSummary({ bundles, skills }) {
  const perPlugin = Object.entries(bundles)
    .map(([bundle, spec]) => `[${bundle}](${CATALOG_DIR}/skills.md#${bundle}) (${(spec.skills || []).length})`)
    .join(' · ');
  return [
    `**${count(skills, 'skill')}** across ${count(Object.keys(bundles), 'plugin')}: ${perPlugin}.`,
    '',
    `👉 **[Browse the skill catalog](${CATALOG_DIR}/skills.md)** for what each one does and the templates it ships with.`,
  ].join('\n');
}

function commandsSummary({ commands }) {
  return `👉 **[Browse all ${count(commands, 'command')}](${CATALOG_DIR}/commands.md)**, with what each one does and the agent it hands off to.`;
}

function agentsSummary({ agents }) {
  return `👉 **[Browse all ${count(agents, 'agent')}](${CATALOG_DIR}/agents.md)**, with what each may do (edit files, run commands, drive a browser) and how to call it in each tool.`;
}

function rulesSummary({ rules }) {
  return `👉 **[Browse all ${count(rules, 'rule')}](rules/README.md)**, with the files each applies to, in Copilot, Claude Code and Codex format.`;
}

function packsCatalog({ packs }) {
  const out = ['| Pack | What it does | Agents | Start it | Install id |', '| --- | --- | :---: | --- | --- |'];
  for (const pack of packs) {
    const orchestrator = pack.agents.find((a) => a.slug === pack.data.orchestrator);
    out.push(
      `| 🎼 **[${pack.data.title}](plugins/${pack.slug}/)** | ${firstSentence(pack.data.description)} | ${pack.agents.length} | ` +
        `Copilot: **${orchestrator.data.title}** agent<br>Claude Code: \`/${pack.slug}\`<br>Codex: \`$${pack.slug}\` | \`${pack.slug}@jaktestowac\` |`,
    );
  }
  return out.join('\n');
}

function guidesCatalog({ bundles, guidesByName }) {
  const out = ['| Guide | What it covers | Plugin |', '| --- | --- | --- |'];
  for (const [bundle, spec] of Object.entries(bundles)) {
    for (const name of spec.guides || []) {
      const guide = guidesByName.get(name);
      out.push(
        `| 📘 **[${guide.title}](plugins/${bundle}/guides/${name}.md)** | ${firstSentence(guide.summary)} | \`${bundle}\` |`,
      );
    }
  }
  return out.join('\n');
}

function hooksCatalog({ hooks }) {
  const out = ['| Hook | What it does | Claude Code | Copilot |', '| --- | --- | --- | :---: |'];
  for (const { slug, data } of hooks) {
    const claude = data.hosts.includes('claude') ? `\`/plugin install ${slug}@jaktestowac\`` : '—';
    const copilot = data.hosts.includes('copilot') ? `[📁](hooks/copilot/.github/hooks/${slug}/)` : '—';
    out.push(`| **${data.title || slug}** | ${firstSentence(data.description)} | ${claude} | ${copilot} |`);
  }
  return out.join('\n');
}

function renderReadme(current, context) {
  const renderers = {
    BADGES: badges,
    PLUGINS: plugins,
    GUIDES: guidesCatalog,
    SKILLS: skillsSummary,
    COMMANDS: commandsSummary,
    AGENTS: agentsSummary,
    PACKS: packsCatalog,
    RULES: rulesSummary,
    HOOKS: hooksCatalog,
  };
  let text = current;
  for (const section of SECTIONS) {
    const start = `<!-- START_${section} -->`;
    const end = `<!-- END_${section} -->`;
    const pattern = new RegExp(`${start}[\\s\\S]*?${end}`);
    if (!pattern.test(text)) throw new Error(`README.md: missing ${start} ... ${end} markers`);
    text = text.replace(pattern, () => `${start}\n\n${renderers[section](context)}\n\n${end}`);
  }
  return text;
}

// --- catalog pages ------------------------------------------------------------------------------

function page(title, intro, body) {
  return `${GENERATED}\n\n# ${title}\n\n${intro}\n\n${body}\n`;
}

function renderCatalog(context) {
  const base = '../';
  const { skills, commands, agents, rules } = context;
  return {
    [`${CATALOG_DIR}/README.md`]: page(
      '📚 Catalog',
      'Everything in this collection, one page per kind. Back to the [main README](../README.md).',
      [
        '| Page | What is on it |',
        '| --- | --- |',
        `| [Skills](skills.md) | ${count(skills, 'skill')}, grouped by plugin |`,
        `| [Commands](commands.md) | ${count(commands, 'command')} you run yourself |`,
        `| [Agents](agents.md) | ${count(agents, 'agent')} you hand a whole job to |`,
        `| [Rules](../rules/README.md) | ${count(rules, 'rule')} applied while matching files are edited |`,
      ].join('\n'),
    ),
    [`${CATALOG_DIR}/skills.md`]: page(
      '📚 Skills',
      [
        'Every skill, grouped by the plugin it ships in. Your agent loads a skill on its own when your request matches its description.',
        '',
        'Click a name to read the skill. A 📎 links to the templates, checklists or examples it ships with. Back to the [catalog](README.md) or the [main README](../README.md).',
      ].join('\n'),
      skillsTables(context, base),
    ),
    [`${CATALOG_DIR}/commands.md`]: page(
      '⌨️ Commands',
      [
        'Commands are ready-made prompts you run yourself. Type the command, then what it should work on; if something it needs is missing, it asks.',
        '',
        '| Tool | How to run |',
        '| --- | --- |',
        '| Claude Code, GitHub Copilot | `/fix-tests tests/checkout` |',
        '| OpenAI Codex | `$fix-tests tests/checkout` |',
        '',
        'Commands never start on their own, so they don\'t compete with the skills. Many hand the work to one of the [agents](agents.md) from the same plugin. Back to the [catalog](README.md) or the [main README](../README.md).',
      ].join('\n'),
      commandsTable(context, base),
    ),
    [`${CATALOG_DIR}/agents.md`]: page(
      '🤖 Agents',
      [
        'Agents are specialists with their own instructions and a fixed set of tools. Hand one a whole job and it works through it end to end. Each ships in the plugin listed next to it.',
        '',
        '**Can:** ✏️ edits files · ▶️ runs commands · 🌐 browses the web · 🤝 hands work to other agents · 🎭 drives a browser through Playwright MCP. Every agent can read and search your project.',
        '',
        '| Tool | How to call an agent |',
        '| --- | --- |',
        '| Claude Code | Ask for it by name ("use the test-code-reviewer agent"), or type `@` and pick it. Claude Code also delegates to it on its own when your request matches its description. |',
        '| GitHub Copilot | Pick it from the agent dropdown in the chat view. |',
        '| OpenAI Codex | Copy the plugin\'s `codex/agents/*.toml` files into `.codex/agents/`, then ask Codex to spawn the agent by name. Names use underscores, for example `test_code_reviewer`. |',
        '',
        'Back to the [catalog](README.md) or the [main README](../README.md).',
      ].join('\n'),
      agentsTable(context, base),
    ),
  };
}

module.exports = { renderReadme, renderCatalog, CATALOG_DIR };
